'use strict';
/** Shared, deterministic family multiplayer policy. No outside player supplied commands. */
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const ROOMS=Object.freeze([
 {id:1,title:'Casa Azul',x0:64,x1:82,z0:82,z1:99,spawn:{x:81,y:45,z:90}},
 {id:2,title:'Casa Vermelha',x0:118,x1:138,z0:82,z1:99,spawn:{x:119,y:45,z:90}},
 {id:3,title:'Casa Amarela',x0:69,x1:88,z0:122,z1:141,spawn:{x:87,y:45,z:131}},
 {id:4,title:'Casa Rosa',x0:109,x1:131,z0:121,z1:140,spawn:{x:119,y:45,z:122}}
]);
const SKINS=Object.freeze({azul:'Azul',verde:'Verde',rosa:'Rosa',roxo:'Roxo'});
const palette=Object.freeze({
 azul:{shirt:[48,116,225],hair:[65,40,30],pants:[35,61,127]},
 verde:{shirt:[30,171,116],hair:[43,31,28],pants:[27,83,61]},
 rosa:{shirt:[231,95,159],hair:[93,48,42],pants:[129,55,112]},
 roxo:{shirt:[131,83,207],hair:[64,49,34],pants:[60,54,121]}
});
function playerName(u){
 const clean=String(u.name).normalize('NFD').replace(/[\u0300-\u036f]/g,'').replace(/[^A-Za-z0-9]/g,'').slice(0,11)||'Piloto';
 return clean+'_'+String(u.id).replace(/-/g,'').slice(0,4);
}
function initHomes(state){
 if(state.minecraftHouses&&typeof state.minecraftHouses==='object')return false;
 state.minecraftHouses={};
 const children=state.users.filter(u=>u.role==='child'&&u.enabled);
 ROOMS.forEach((room,i)=>{if(children[i])state.minecraftHouses[room.id]=children[i].id});
 return true;
}
function familyInfo(state,u,connected){
 const users=state.users.filter(p=>p.enabled&&(p.role==='child'||p.role==='admin'));
 const players=users.map(p=>({
  id:p.id,name:p.name,playerName:playerName(p),online:connected.has(p.id),me:p.id===u.id,
  role:p.role,skin:SKINS[(state.minecraftSkins||{})[p.id]]?(state.minecraftSkins||{})[p.id]:'azul'
 }));
 const homes=ROOMS.map(r=>{
  const owner=users.find(v=>v.id===state.minecraftHouses?.[r.id]);
  return {id:r.id,title:r.title,ownerId:owner?.id||null,ownerName:owner?.name||null,mine:owner?.id===u.id};
 });
 return {players,homes,skins:SKINS,worlds:[{id:'vila',title:'Vila da Família'},{id:'aventura',title:'Mundo Aventura'}]};
}
function policyText(state){
 const lines=['# GamesForChildren family policy; generated by the authenticated Node server'];
 for(const u of state.users.filter(u=>u.enabled&&(u.role==='child'||u.role==='admin')))
  lines.push(['U',playerName(u),u.role].join('|'));
 lines.push(['S','building',state.minecraftControls?.buildingEnabled===false?'false':'true'].join('|'));
 for(const h of ROOMS){
  const owner=state.users.find(u=>u.id===state.minecraftHouses?.[h.id]&&u.enabled);
  lines.push(['H',h.id,owner?playerName(owner):'-'].join('|'));
 }
 return lines.join('\n')+'\n';
}
function writePolicy(state,mcDir){
 const folder=path.join(mcDir,'properties');fs.mkdirSync(folder,{recursive:true,mode:0o700});
 const filename=path.join(folder,'gfc-family-policy.txt'),text=policyText(state);
 try{if(fs.readFileSync(filename,'utf8')===text)return false}catch(e){if(e.code!=='ENOENT')throw e}
 const tmp=filename+'.'+process.pid+'.'+crypto.randomBytes(3).toString('hex')+'.tmp';
 fs.writeFileSync(tmp,text,{mode:0o600});fs.renameSync(tmp,filename);
 return true;
}
function rgba(r,g,b,a=255){return [r,g,b,a]}
const CRC_TABLE=Array.from({length:256},(_,n)=>{
 let c=n;for(let k=0;k<8;k++)c=c&1?0xedb88320^(c>>>1):c>>>1;return c>>>0;
});
function crc32(buf){let c=0xffffffff;for(const b of buf)c=CRC_TABLE[(c^b)&255]^(c>>>8);return (c^0xffffffff)>>>0}
function chunk(name,data){const tag=Buffer.from(name,'ascii'),size=Buffer.alloc(4),sum=Buffer.alloc(4);size.writeUInt32BE(data.length);sum.writeUInt32BE(crc32(Buffer.concat([tag,data])));return Buffer.concat([size,tag,data,sum])}
function makeSkin(slug){
 const theme=palette[slug];if(!theme)throw Error('Invalid skin');
 const w=64,h=32,raw=Buffer.alloc(h*(1+w*4),0);
 const color=(x,y,c)=>{
  if(x<0||y<0||x>=w||y>=h)return;
  const pos=y*(1+w*4)+1+x*4;for(let j=0;j<4;j++)raw[pos+j]=c[j];
 };
 const fill=(x0,y0,x1,y1,c)=>{for(let y=y0;y<=y1;y++)for(let x=x0;x<=x1;x++)color(x,y,c)};
 const skin=rgba(244,190,144),shade=rgba(216,146,108),hair=rgba(...theme.hair),
  shirt=rgba(...theme.shirt),shirtDark=rgba(...theme.shirt.map(n=>Math.round(n*.78))),
  trouser=rgba(...theme.pants),shoes=rgba(38,45,61),eye=rgba(43,60,73);
 // Head: classic 64x32 player skin UV layout.
 fill(0,0,31,15,skin);fill(0,0,31,7,hair);
 fill(8,8,15,10,hair);fill(8,11,15,15,skin);
 color(10,12,eye);color(13,12,eye);fill(11,14,12,14,shade);
 // Body (left/right/front/back), sleeves and pants.
 fill(16,16,39,31,shirt);fill(16,16,39,19,shirtDark);
 fill(40,16,55,31,shirt);fill(40,16,55,19,shirtDark);
 fill(0,16,15,31,trouser);
 fill(0,29,15,31,shoes);
 // Tunic motif on the front of the torso.
 fill(23,21,24,24,rgba(245,235,157));
 const ihdr=Buffer.alloc(13);ihdr.writeUInt32BE(w,0);ihdr.writeUInt32BE(h,4);ihdr[8]=8;ihdr[9]=6;
 return Buffer.concat([Buffer.from([137,80,78,71,13,10,26,10]),chunk('IHDR',ihdr),chunk('IDAT',require('node:zlib').deflateSync(raw,{level:9})),chunk('IEND',Buffer.alloc(0))]);
}
